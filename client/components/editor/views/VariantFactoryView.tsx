'use client'

import React, { useState } from 'react'
import { m } from 'framer-motion'
import { Zap, Target, ArrowRight, Shuffle, RotateCcw, Loader2 } from 'lucide-react'
import { generateHooks, type Hook } from '../../../lib/featuresApi'
import { handleApiError } from '../../../lib/api'
import { useTranslation } from '../../../hooks/useTranslation'

export type HookVariant = Hook

interface VariantFactoryViewProps {
  /** The video's transcript (or script) the hooks are written for. */
  topic: string
  onApplyVariant: (variant: HookVariant) => void
  onBack: () => void
}

/**
 * Hook variants for the current video, generated by the real hook generator
 * (POST /api/hooks). It used to wait two seconds and show the same three
 * hard-coded hooks with invented "94% retention / 98 viral score" numbers —
 * the generator returns hook text and style only, so that is all we show.
 */
const VariantFactoryView: React.FC<VariantFactoryViewProps> = ({ topic, onApplyVariant, onBack }) => {
  const { t } = useTranslation()
  const [isGenerating, setIsGenerating] = useState(false)
  const [variants, setVariants] = useState<HookVariant[]>([])
  const [error, setError] = useState<string | null>(null)

  const hasTopic = topic.trim().length > 0

  const handleGenerate = async () => {
    if (!hasTopic) {
      setError(t('variantFactory.needsTranscript'))
      return
    }
    setIsGenerating(true)
    setError(null)
    try {
      const result = await generateHooks({ topic, platform: 'tiktok', style: 'mix', count: 3 })
      const hooks = Array.isArray(result?.hooks) ? result.hooks.filter(h => h && h.text) : []
      setVariants(hooks)
      if (hooks.length === 0) setError(t('variantFactory.noHooks'))
    } catch (err) {
      setError(handleApiError(err) || t('variantFactory.failed'))
    } finally {
      setIsGenerating(false)
    }
  }

  return (
    <div className="h-full flex flex-col space-y-8">
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-3">
          <Target className="w-5 h-5 text-fuchsia-400" />
          <h2 className="text-lg font-bold tracking-tight text-[var(--text-main)]">{t('variantFactory.title')}</h2>
        </div>
        <button
          type="button"
          onClick={onBack}
          className="text-[11px] font-semibold text-slate-500 hover:text-white transition-colors flex items-center gap-2"
        >
          <RotateCcw className="w-3 h-3" />
          {t('variantFactory.back')}
        </button>
      </div>

      <p className="text-[12px] font-medium text-slate-400 leading-relaxed border-l-2 border-fuchsia-500/30 pl-4">
        {t('variantFactory.description')}
      </p>

      {error && <p className="text-sm text-rose-500" role="alert">{error}</p>}

      {isGenerating ? (
        <div className="flex-1 flex flex-col items-center justify-center gap-4 py-12">
          <Loader2 className="w-8 h-8 text-fuchsia-400 animate-spin" aria-hidden />
          <span className="text-sm font-medium text-slate-300">{t('variantFactory.generating')}</span>
        </div>
      ) : variants.length === 0 ? (
        <div className="flex-1 flex flex-col items-center justify-center space-y-6 py-12">
          <div className="w-24 h-24 rounded-full bg-white/[0.02] border border-white/5 flex items-center justify-center">
            <Shuffle className="w-10 h-10 text-slate-600" aria-hidden />
          </div>
          <button
            type="button"
            onClick={handleGenerate}
            disabled={!hasTopic}
            className="px-10 py-5 rounded-2xl bg-fuchsia-600 hover:bg-fuchsia-500 disabled:opacity-50 disabled:cursor-not-allowed transition-all flex items-center gap-3"
          >
            <Zap className="w-5 h-5 text-white" aria-hidden />
            <span className="text-sm font-semibold text-white">{t('variantFactory.generate')}</span>
          </button>
          {!hasTopic && <p className="text-xs text-slate-500">{t('variantFactory.needsTranscript')}</p>}
        </div>
      ) : (
        <div className="space-y-4">
          {variants.map((variant, i) => (
            <m.div
              key={`${i}-${variant.text}`}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: i * 0.1 }}
              className="p-6 rounded-[2rem] bg-white/[0.02] border border-white/5 hover:border-fuchsia-500/30 transition-all"
            >
              {variant.style && (
                <span className="inline-block px-3 py-1 mb-3 rounded-full text-[10px] font-semibold capitalize bg-white/5 text-slate-400">
                  {variant.style}
                </span>
              )}
              <h3 className="text-lg font-bold text-[var(--text-main)] leading-tight">
                &quot;{variant.text}&quot;
              </h3>
              <button
                type="button"
                onClick={() => onApplyVariant(variant)}
                className="mt-6 w-full py-3 rounded-xl bg-white/5 border border-white/10 hover:bg-white hover:text-black transition-all flex items-center justify-center gap-2 group/btn"
              >
                <span className="text-[11px] font-semibold">{t('variantFactory.apply')}</span>
                <ArrowRight className="w-3 h-3 group-hover/btn:translate-x-1 transition-transform" aria-hidden />
              </button>
            </m.div>
          ))}

          <div className="pt-2 flex justify-center">
            <button
              type="button"
              onClick={handleGenerate}
              className="text-[11px] font-semibold text-slate-400 hover:text-white transition-colors flex items-center gap-2"
            >
              <Shuffle className="w-3 h-3" aria-hidden />
              {t('variantFactory.regenerate')}
            </button>
          </div>
        </div>
      )}
    </div>
  )
}

export default VariantFactoryView
